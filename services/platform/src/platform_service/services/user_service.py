def get_all_users() -> list[dict[str, Any]]:
    """Return a flat list of all unique users mapped from RAW_DATA."""
    users = []
    seen = set()

    # 1. Area Managers (AM)
    for row in RAW_DATA:
        am_id = int(row[3])
        if am_id not in seen:
            seen.add(am_id)
            users.append(
                {
                    "id": am_id,
                    "name": row[2],
                    "role": "AM",
                    "district": row[0],
                    "upazila": None,
                    "parent_id": None,
                }
            )

    # 2. Program Organizers (PO)
    for row in RAW_DATA:
        po_id = int(row[5])
        am_id = int(row[3])
        if po_id not in seen:
            seen.add(po_id)
            users.append(
                {
                    "id": po_id,
                    "name": row[4],
                    "role": "PO",
                    "district": row[0],
                    "upazila": row[1],
                    "parent_id": am_id,
                }
            )

    # 3. Shasthya Kormis (SK)
    for row in RAW_DATA:
        sk_id = int(row[7])
        po_id = int(row[5])
        if sk_id not in seen:
            seen.add(sk_id)
            users.append(
                {
                    "id": sk_id,
                    "name": row[6],
                    "role": "SK",
                    "district": row[0],
                    "upazila": row[1],
                    "parent_id": po_id,
                }
            )

    return users


# Map of SK user_id to PO user_id
SK_TO_PO_MAP = {row[7]: row[5] for row in RAW_DATA}


def get_user_po_id(user_id: int) -> int | None:
    """Return the PO user_id for a given SK user_id, or None if not found/not an SK."""
    return SK_TO_PO_MAP.get(user_id)


def get_team_members_for_organizer(organizer_id: int) -> list[dict[str, Any]]:
    """Return SK team members whose parent_id matches the organizer (PO) user id."""
    return [u for u in get_all_users() if u["role"] == "SK" and u["parent_id"] == organizer_id]


def get_all_sk_users() -> list[dict[str, Any]]:
    """Return all SK-role users (unrestricted team-activity roster when auth is off)."""
    return [u for u in get_all_users() if u["role"] == "SK"]
